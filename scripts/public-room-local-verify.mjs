// Reuse Wiki Race's already-pinned LOCAL Docker/Supabase database.
// Never link, reset, repair, or contact a production database.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  TARGET_PROJECT_ID, EXPECTED_CLI_VERSION, expectedDbContainer,
  inspectContainer, readProjectId, repoRoot, runCli, runProcess, runPsql,
} from './supabase-runtime-common.mjs';
import { parseTapTranscript } from './supabase-runtime-validation.mjs';

const args = new Set(process.argv.slice(2));
const checkOnly = args.has('--check-only');
if ([...args].some(a => !['--check-only'].includes(a))) {
  throw new Error('UNKNOWN_ARG: supported flag is --check-only');
}
process.chdir(repoRoot);

function requireSuccess(result, label) {
  if (result.status !== 0) {
    if (result.stderr) console.error(result.stderr.trimEnd());
    if (result.stdout) console.error(result.stdout.trimEnd());
    throw new Error(label + ' FAILED (exit=' + result.status + ')');
  }
  return result.stdout;
}
function state(label, message) { console.log('[LOCAL] ' + label + ': ' + message); }

const projectId = readProjectId();
if (projectId !== TARGET_PROJECT_ID) throw new Error('REFUSED: incorrect local project_id');
const config = fs.readFileSync(path.join(repoRoot, 'supabase', 'config.toml'), 'utf8');
if (!config.includes('port = 54321') || !config.includes('port = 54322')) {
  throw new Error('REFUSED: unexpected local API/DB port');
}
const container = expectedDbContainer(projectId);
const inspection = inspectContainer(container);
requireSuccess(inspection, 'LOCAL DOCKER CONTAINER');
const details = JSON.parse(inspection.stdout.trim());
if (details.State?.Status !== 'running' || details.State?.Health?.Status !== 'healthy') {
  throw new Error('LOCAL DOCKER CONTAINER NOT HEALTHY: start the pinned stack first');
}
state('container', container + ' running/healthy');
const cli = requireSuccess(runCli(['--version']), 'PINNED SUPABASE CLI').trim();
if (cli !== EXPECTED_CLI_VERSION) throw new Error('REFUSED: unexpected CLI ' + cli);
state('CLI', cli);

// Existing preflight verifies pinned image identity/digest before any DB SQL.
requireSuccess(runProcess(process.execPath, [
  fileURLToPath(new URL('./supabase-runtime-preflight.mjs', import.meta.url)), '--bootstrap',
], { cwd: repoRoot, timeout: 120000 }), 'PINNED IMAGE PREFLIGHT');
state('preflight', 'passed; production unchanged');
if (checkOnly) {
  state('check-only', 'no migrations or database tests were run');
  process.exit(0);
}

const migrationPath = 'supabase/migrations/20261030010000_public_room_discovery_v1.sql';
const testPath = 'supabase/tests/public_room_discovery_v1.sql';
if (!fs.existsSync(path.join(repoRoot, migrationPath))
  || !fs.existsSync(path.join(repoRoot, testPath))) throw new Error('PUBLIC_ROOM_SQL_NOT_FOUND');

state('migration', 'applying pending migrations only to pinned LOCAL Docker project');
const pushed = runCli(['--workdir', repoRoot, 'db', 'push', '--local',
  '--include-all', '--skip-vault', '--yes'], { timeout: 15 * 60_000 });
requireSuccess(pushed, 'LOCAL MIGRATION PUSH');
state('migration', 'local apply complete');

const sql = fs.readFileSync(path.join(repoRoot, testPath), 'utf8');
const result = runPsql(container, sql, { timeout: 120000 });
requireSuccess(result, 'LOCAL PG TAP');
const tap = result.stdout.replace(/\r\n/g, '\n');
const plan = [...tap.matchAll(/^\s*1\.\.(\d+)\s*$/gm)].map(m => Number(m[1]));
if (plan.length !== 1 || !plan[0]) throw new Error('PGTAP_PLAN_MISSING: ' + tap.slice(-2500));
const validated = parseTapTranscript(tap, plan[0]);
if (!validated.pass) {
  console.error(tap);
  throw new Error('PGTAP_FAILED ' + validated.detail);
}
state('pgTAP', validated.detail + ' (fixtures rolled back)');

// Only create mode-scoped, gitignored local Vite configuration.
// Never overwrite regular .env / .env.local or surface any keys in logs.
const status = requireSuccess(runCli(['--workdir', repoRoot, 'status', '-o', 'env']), 'LOCAL STATUS');
const env = Object.fromEntries(status.split(/\r?\n/).map(line => {
  const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
  return m ? [m[1], m[2].replace(/^['"]|['"]$/g, '')] : [];
}).filter(x => x.length === 2));
const url = env.API_URL || '';
const key = env.ANON_KEY || env.PUBLISHABLE_KEY || '';
if (!['http://127.0.0.1:54321', 'http://localhost:54321'].includes(url) || !key) {
  throw new Error('REFUSED: status output does not identify expected LOCAL API and public key');
}
const output = path.join(repoRoot, '.env.publicroom.local');
const marker = '# generated by scripts/public-room-local-verify.mjs';
if (fs.existsSync(output) && !fs.readFileSync(output, 'utf8').startsWith(marker)) {
  throw new Error('REFUSED: existing .env.publicroom.local belongs to another user/process');
}
fs.writeFileSync(output, [
  marker, 'VITE_SUPABASE_URL=' + url,
  'VITE_SUPABASE_ANON_KEY=' + key, '',
].join('\n'), { mode: 0o600 });
state('Vite', 'wrote gitignored .env.publicroom.local; no production URL');
state('next', 'Terminal 1: npx --no-install supabase functions serve');
state('next', 'Terminal 2: npm run dev -- --mode publicroom --host 127.0.0.1');
state('URL', 'http://127.0.0.1:5173 (create 2 duel / 3 group local accounts)');
