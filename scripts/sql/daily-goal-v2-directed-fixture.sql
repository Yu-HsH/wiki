-- ONLY isolated PostgreSQL fixture: extra objects referenced by the actual daily authority RPC.
create schema if not exists private;
do $roles$
begin
 if not exists (select 1 from pg_catalog.pg_roles where rolname='anon') then create role anon nologin; end if;
 if not exists (select 1 from pg_catalog.pg_roles where rolname='authenticated') then create role authenticated nologin; end if;
 if not exists (select 1 from pg_catalog.pg_roles where rolname='service_role') then create role service_role nologin; end if;
end $roles$;
create or replace function private.normalize_wiki_title(t text) returns text language sql immutable as $f$
  select lower(btrim(t));
$f$;
