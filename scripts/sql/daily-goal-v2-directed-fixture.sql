);
create table public.wiki_snapshot_links (
 snapshot_id bigint not null references public.wiki_page_snapshots(id),
 target_page_id bigint not null,
 target_title_snapshot text not null
);
create index on public.wiki_page_snapshots(page_id);
create index on public.wiki_snapshot_links(snapshot_id);
create index on public.wiki_snapshot_links(target_page_id);
