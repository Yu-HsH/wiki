const tiers={normal:0,enhanced:1,weakened:2};
export function itemRaceRule(itemId,tier,mode) {
  const rule=Object.hasOwn(itemRules,itemId) ? itemRules[itemId] : null;
  if (!rule) return [];
  const condition=itemId==='parry' ? `공격 경고 후 ${mode==='duel'?'2초':'표시된 제한 시간'} 안에 패링을 누릅니다.` : rule[3];
  return [rule[tiers[tier]??0],condition];
}
